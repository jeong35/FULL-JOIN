import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const promptPath = new URL("src/fulljoin/prompts/parse_query.md", root);
const schemaPath = new URL("src/fulljoin/schemas/style_image.schema.json", root);
const outputPath = new URL("supabase/functions/api/generated_analysis_contract.ts", root);

const promptDocument = await readFile(promptPath, "utf8");
const lines = promptDocument.split(/\r?\n/);
const start = lines.indexOf("<!-- prompt:start -->");
const end = lines.indexOf("<!-- prompt:end -->");
assert(start >= 0 && end > start, "분석 프롬프트 마커를 찾지 못했어요");
const systemPrompt = lines.slice(start + 1, end).join("\n").trim();

const schema = JSON.parse(await readFile(schemaPath, "utf8"));
delete schema.$schema;
delete schema.title;

const generated = `// Generated by scripts/generate-analysis-contract.mjs. Do not edit by hand.\n` +
  `export const ANALYSIS_SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};\n\n` +
  `export const ANALYSIS_JSON_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  assert.equal(current, generated, "분석 프롬프트 또는 스키마가 바뀌었어요. npm run generate:analysis-contract를 실행해 주세요");
} else {
  await writeFile(outputPath, generated);
  console.log("Generated supabase/functions/api/generated_analysis_contract.ts");
}
