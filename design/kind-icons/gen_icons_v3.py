    shape = sym(r)
    left = 2 * C - body
    lines = [line([(left + 0.6, y), (C, y + 0.7), (body - 0.6, y)]) for y in segs]
    # 소매 누빔: 안쪽(48~49) → 바깥(52.4~54)
