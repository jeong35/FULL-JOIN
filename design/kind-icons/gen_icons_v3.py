"""오딧 옷 종류 그림 v3 (11/7) — 곡선으로 다시 그림.
참고: 은재님이 보낸 일러스트의 '선' — 어깨·소매·밑단이 곡선, 진한 테두리, 칼라·라펠·주머니·시보리 디테일,
오른쪽 그림자, 목 안쪽은 어둡게.

층(아래→위):
  straps  옷 색 굵은 선(가방 끈)
  shapes  옷 색으로 칠하고 테두리를 두르는 면
  shade   그림자(옷 모양 안으로 잘림)
  inner   옷 안쪽(목 안·후드 안). 진한 반투명
  tops    옷 색으로 칠하고 테두리를 두르는 위쪽 면(라펠·칼라·주머니 덮개 등)
  details 솔기·주름·시보리 선(옷 모양 안으로 잘림)
  dots    단추
점은 (x, y) 또는 (x, y, 'c'). 'c'는 꺾이는 점, 나머지는 부드럽게 이어진다.
사용: python3 gen_icons_v3.py icons.json
"""
import json
