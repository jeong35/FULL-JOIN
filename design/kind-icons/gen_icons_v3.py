C = 32
K = 1 / 6  # Catmull-Rom → 베지어 강도


def fmt(v):
    return ("%.1f" % v).rstrip("0").rstrip(".") if abs(v - round(v, 1)) < 1e-9 or True else str(v)


def norm(p):
    return (p[0], p[1], len(p) > 2 and (p[2] == "c" or p[2] is True))


def mir(p):
    p = norm(p)
    return (2 * C - p[0], p[1], p[2])


FILLET = 0.9  # 꺾이는 점을 이만큼 둥글게 깎는다(닫힌 모양만)


def fillet(pts):
    """꺾이는 점 P를 앞뒤로 r만큼 떨어진 두 점으로 바꾸고, 그 사이를 P를 조절점으로 둥글게 잇는다."""
    import math
    n, out = len(pts), []
    for i, p in enumerate(pts):
        if not p[2]:
            out.append(p)
            continue
        a, b = pts[i - 1], pts[(i + 1) % n]
        va, vb = (a[0] - p[0], a[1] - p[1]), (b[0] - p[0], b[1] - p[1])
        la, lb = math.hypot(*va), math.hypot(*vb)
        if la < 1e-6 or lb < 1e-6:
            out.append(p)
            continue
        cos = (va[0] * vb[0] + va[1] * vb[1]) / (la * lb)
        if cos < -0.995:  # 거의 직선이면 그대로
            out.append(p)
            continue
        r = min(FILLET, la * 0.4, lb * 0.4)
        p1 = (p[0] + va[0] / la * r, p[1] + va[1] / la * r, "f1", p)
        p2 = (p[0] + vb[0] / lb * r, p[1] + vb[1] / lb * r, "f2", p)
        out += [p1, p2]
    return out


def bez(pts, closed=True):
    pts = [norm(p) for p in pts]
    if closed:
        pts = fillet(pts)
    n = len(pts)

    def P(i):
        return pts[i % n] if closed else pts[max(0, min(n - 1, i))]

    d = f"M{fmt(pts[0][0])},{fmt(pts[0][1])}"
    for i in range(n if closed else n - 1):
        p0, p1, p2, p3 = P(i - 1), P(i), P(i + 1), P(i + 2)
        if p1[2] == "f1" and p2[2] == "f2":  # 둥근 모서리
            cx, cy = p1[3][0], p1[3][1]
            c1 = (p1[0] + (cx - p1[0]) * 2 / 3, p1[1] + (cy - p1[1]) * 2 / 3)
            c2 = (p2[0] + (cx - p2[0]) * 2 / 3, p2[1] + (cy - p2[1]) * 2 / 3)
            d += f" C{fmt(c1[0])},{fmt(c1[1])} {fmt(c2[0])},{fmt(c2[1])} {fmt(p2[0])},{fmt(p2[1])}"
            continue
        if p1[2] and p2[2]:
            d += f" L{fmt(p2[0])},{fmt(p2[1])}"
            continue
        c1 = (p1[0], p1[1]) if p1[2] else (p1[0] + (p2[0] - p0[0]) * K, p1[1] + (p2[1] - p0[1]) * K)
        c2 = (p2[0], p2[1]) if p2[2] else (p2[0] - (p3[0] - p1[0]) * K, p2[1] - (p3[1] - p1[1]) * K)
        d += f" C{fmt(c1[0])},{fmt(c1[1])} {fmt(c2[0])},{fmt(c2[1])} {fmt(p2[0])},{fmt(p2[1])}"
    return d + (" Z" if closed else "")


def sym(right):
    """오른쪽 반(가운데 위 → 가운데 아래)만 주면 거울로 붙인 닫힌 모양."""
    full = list(right) + [mir(p) for p in reversed(right[1:-1])]
    return bez(full, True)


def line(pts):
    return bez(pts, False)


def pair(pts):
    return [line(pts), line([mir(p) for p in pts])]


def pair_shape(pts):
    return [bez(pts, True), bez([mir(p) for p in pts], True)]


def rect(x0, y0, x1, y1):
    return f"M{fmt(x0)},{fmt(y0)} L{fmt(x1)},{fmt(y0)} L{fmt(x1)},{fmt(y1)} L{fmt(x0)},{fmt(y1)} Z"


def ticks(y0, y1, x0, x1, step=2.2):
    out, x = [], x0 + step
    while x < x1 - 0.6:
        out.append(f"M{fmt(x)},{fmt(y0)} L{fmt(x)},{fmt(y1)}")
        x += step
    return out


def mirror_d(d):
    """path 문자열의 x를 뒤집는다(M L C Z만)."""
    import re
    toks = re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", d)
    out, idx = [], 0
    for t in toks:
        if t in "MLCZ":
            out.append(t)
            idx = 0
            continue
        v = float(t)
        out.append(fmt(2 * C - v) if idx % 2 == 0 else fmt(v))
        idx += 1
    s, i = "", 0
    while i < len(out):
        t = out[i]
        if t in "MLCZ":
            s += (" " if s else "") + t
            i += 1
            first = True
            while i < len(out) and out[i] not in "MLCZ":
                s += ("" if first else " ") + out[i] + "," + out[i + 1]
                first = False
                i += 2
        else:
            i += 1
    return s


ICONS = {}


def add(kind, shapes, details=(), shade=(), inner=(), tops=(), dots=(), straps=(), transform=None):
    ic = {"shapes": list(shapes), "details": list(details), "shade": list(shade), "inner": list(inner), "tops": list(tops),
          "dots": [list(x) for x in dots], "straps": list(straps)}
    if transform:
        ic["transform"] = transform
    ICONS[kind] = ic
    return ic


